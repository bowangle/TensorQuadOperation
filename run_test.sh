#!/bin/bash
set -e
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

suite="${1:-all}"
case "$suite" in
    all|TensorQuadOperation|QuanticsIntegration|fft-tn-quadp) ;;
    *) echo "Usage: $0 [TensorQuadOperation|QuanticsIntegration|fft-tn-quadp]" >&2; exit 2 ;;
esac

tensor_tests=(
    test
    test_Mat_QR
    test_Mat_SVDDecomp
    test_Tensor3D
    test_tt_base
    test_mps
    test_ttn
    test_compress_svd
    test_mpo
    test_convolution
    test_analytics_construction
)
integration_tests=(
    test_indefinite_integral
    test_quantics_integrator
    test_quantics_integrator_kD
    test_simplex_integration
)

fft_tests=(
    test_magic_qft_mpo
    test_general_integrator
    test_fft_param
    test_fft_vanilla
    test_fft_double
    test_fft_convergence_double
    test_fft_convergence_dd128
    test_fft_phase_dd128
    test_fft_dd128
    test_fft_float128
)

pids=()
names=()
status=0
run_group() {
    local group="$1"
    shift
    local name log_name target log_file
    for name in "$@"; do
        log_name="$name"
        # Preserve the historical filename for the TT base test log.
        if [[ "$name" == test_tt_base ]]; then
            log_name=test_TT_base
        fi
        log_file="test/$group/$log_name.txt"
        if [[ "$group" == fft-tn-quadp ]]; then
            # Run serially: missing QFT cache files can be generated by multiple tests.
            target="fft_tn_${name}"
            if ! "./build/$target" > "$log_file" 2>&1; then
                echo "FAILED: $group/$name (see $log_file)" >&2
                status=1
            fi
        else
            target="tq_test_${name}"
            "./build/$target" > "$log_file" 2>&1 &
            pids+=("$!")
            names+=("$group/$name")
        fi
    done
}

if [[ "$suite" == all || "$suite" == TensorQuadOperation ]]; then
    run_group TensorQuadOperation "${tensor_tests[@]}"
fi
if [[ "$suite" == all || "$suite" == QuanticsIntegration ]]; then
    run_group QuanticsIntegration "${integration_tests[@]}"
fi
if [[ "$suite" == all || "$suite" == fft-tn-quadp ]]; then
    run_group fft-tn-quadp "${fft_tests[@]}"
fi

# Wait for every child explicitly so a failing test cannot be hidden by bare wait.
for index in "${!pids[@]}"; do
    if ! wait "${pids[$index]}"; then
        echo "FAILED: ${names[$index]} (see its log)" >&2
        status=1
    fi
done
if [[ "$status" == 0 ]]; then
    echo "All selected tests completed successfully. Logs are in the corresponding test subfolders."
else
    echo "Some tests failed. Check the logs in the corresponding test subfolders." >&2
fi
exit "$status"
